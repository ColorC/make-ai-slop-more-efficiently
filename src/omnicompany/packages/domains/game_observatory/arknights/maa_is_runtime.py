class ISRecognitionError(ValueError):
    """Untrusted recognition evidence or activation was rejected."""


class StaleRecognitionError(ISRecognitionError):
    """The physical frame changed while MaaCore was scanning it."""


@dataclass(frozen=True, slots=True)
class RecognitionTargetV1:
    target_id: str
    action: ISActionKind | None
    label: str
    rect: PixelRectV1
    enabled: bool = True
    end_rect: PixelRectV1 | None = None
    duration_ms: int = 300


@dataclass(frozen=True, slots=True)
class RecognizedClipV1:
    task_id: str  # Internal only: MAAISRecognizer never puts this in public output.
    frame_sha256: str
    targets: tuple[RecognitionTargetV1, ...] = ()
    visible_text: tuple[str, ...] = ()


class RecognitionEngine(Protocol):
    def recognize(self, frame_bgr: bytes, clips: tuple[Mapping[str, object], ...]) -> Sequence[RecognizedClipV1]: ...


class SwipeTaskInvoker(Protocol):
    def __call__(self, task_id: str, payload: Mapping[str, object]) -> bool: ...


@dataclass(frozen=True, slots=True)
class RecognitionOverlayV1:
    """Content-addressed host resource; it is intentionally not a contestant asset."""
    root: Path
    manifest_sha256: str
    jobs: Mapping[str, Mapping[str, object]]
    host_task: str
    sentinel_task: str


def _as_bundle(value: InteractionAssetBundleV1 | Mapping[str, object]) -> Mapping[str, object]:
    return value.payload if isinstance(value, InteractionAssetBundleV1) else value


def _job_id(task_id: str) -> str:
    return "Omni@ISR-" + hashlib.sha256(task_id.encode("utf-8")).hexdigest()[:24]


def _default_template(task_id: str) -> str:
    """Materialize MAA's MatchTemplate ``TaskName.png`` default safely."""
    path = PurePosixPath(task_id)
    if (
        not task_id
        or path.is_absolute()
        or path.name != task_id
        or ".." in path.parts
        or "\\" in task_id
        or ":" in task_id
        or "\x00" in task_id
        or task_id.endswith((" ", "."))
    ):
        raise ISRecognitionError("MatchTemplate task id cannot form a safe default template")
    return f"{task_id}.png"


def _recognition_payload(
    task_id: str, payload: Mapping[str, object], next_task: str,
) -> dict[str, object] | None:
    """Copy precisely recognition inputs, never source control/action fields."""
    algorithm = payload.get("algorithm")
    if algorithm not in {"MatchTemplate", "OcrDetect"}:
        return None
    result: dict[str, object] = {"algorithm": algorithm, "action": "DoNothing", "preDelay": 0,
                                 "postDelay": 0, "maxTimes": 1, "next": [next_task],
                                 "onErrorNext": [next_task]}
    # These are recognition inputs in the validated Sami source.  In particular,
    # geometry and delays belong to the source action and must not cross this boundary.
    for key in ("roi", "templThreshold", "maskRange", "template", "text", "fullMatch", "ocrReplace"):
        value = payload.get(key)
        if value is not None:
            result[key] = value
    # MAA resolves a missing MatchTemplate template as ``TaskName.png``.  Jobs
    # have opaque names, so retain that resolved source meaning explicitly.
    if algorithm == "MatchTemplate" and "template" not in payload:
        result["template"] = _default_template(task_id)
    return result


def compile_recognition_overlay(
    bundle: InteractionAssetBundleV1 | Mapping[str, object], destination: Path | str,
) -> RecognitionOverlayV1:
    """Compile a deterministic, non-destructive incremental ``resource`` overlay.

    Existing destinations are accepted only when every generated byte agrees;
    unrelated directories are never altered.
    """
    payload = _as_bundle(bundle)
    try:
        assert_maa_is_interaction_asset_bundle(payload)
    except MaaInteractionAssetError as exc:
        raise ISRecognitionError(str(exc)) from exc
    clips = payload.get("task_clips")
    if not isinstance(clips, list):
        raise ISRecognitionError("invalid task clip inventory")
    sentinel = "Omni@ISR-Sentinel"
    host = "Omni@ISR-Host"
    recognized = [c for c in clips if isinstance(c, Mapping) and
                  isinstance(c.get("payload"), Mapping) and c["payload"].get("algorithm") in {"MatchTemplate", "OcrDetect"}]
    # Reverse construction gives each deterministic job its successor.
    jobs: dict[str, dict[str, object]] = {}
    successor = sentinel
    for clip in reversed(recognized):
        task_id = clip.get("task_id")
        if not isinstance(task_id, str):
            raise ISRecognitionError("malformed task clip")
        job = _recognition_payload(task_id, clip["payload"], successor)  # type: ignore[arg-type]
        if job is None:
            continue
        jid = _job_id(task_id)
        jobs[jid] = job
        successor = jid
    tasks: dict[str, object] = {
        sentinel: {"algorithm": "JustReturn", "action": "DoNothing", "preDelay": 0, "postDelay": 0, "maxTimes": 1},
        host: {"algorithm": "JustReturn", "action": "DoNothing", "preDelay": 0, "postDelay": 0,
               "maxTimes": 1, "next": [successor], "onErrorNext": [successor]},
    }
    tasks.update(jobs)
    manifest = {
        "schema": "omnicompany.maa-is-recognition-overlay.v1",
        "bundle_sha256": InteractionAssetBundleV1(payload).content_sha256,
        "host_task": host,
        "sentinel_task": sentinel,
        # All reviewed clips are indexed, including gesture-only and inert clips.
        "inventory": [
            {"clip_sha256": hashlib.sha256(str(c["task_id"]).encode()).hexdigest(),
             "recognition_job": _job_id(str(c["task_id"])) if c in recognized else None}
            for c in clips if isinstance(c, Mapping)
        ],
        "jobs": {jid: {"source_sha256": hashlib.sha256(str(c["task_id"]).encode()).hexdigest()}
                 for jid, c in ((_job_id(str(c["task_id"])), c) for c in recognized)},
    }
    files = {"resource/tasks/tasks.json": json.dumps(tasks, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode(),
             "recognition-manifest.json": json.dumps(manifest, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()}
    root = Path(destination)
    if root.exists():
        if not root.is_dir() or any(not (root / name).is_file() or (root / name).read_bytes() != data for name, data in files.items()):
            raise ISRecognitionError("recognition overlay destination already exists with different content")
        # Exact means no surprising files *or directories* either.
        actual = {p.relative_to(root).as_posix() for p in root.rglob("*")}
        expected = set(files) | {"resource", "resource/tasks"}
        if actual != expected:
            raise ISRecognitionError("recognition overlay destination contains unrelated content")
    else:
        root.mkdir(parents=True)
        for name, data in files.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    digest = hashlib.sha256(files["recognition-manifest.json"]).hexdigest()
    return RecognitionOverlayV1(root, digest, jobs, host, sentinel)


class MaaCoreRecognitionEngine:
    """Concrete single-channel recognition engine using a generated Custom scan."""
    def __init__(self, operator: MaaOperator, overlay: RecognitionOverlayV1) -> None:
        self._operator, self._overlay = operator, overlay

    @staticmethod
    def _event_value(event: object, name: str) -> object:
        value = getattr(event, name, None)
        return value if value is not None else (event.get(name) if isinstance(event, Mapping) else None)

    def recognize(self, frame_bgr: bytes, clips: tuple[Mapping[str, object], ...]) -> Sequence[RecognizedClipV1]:
        if not isinstance(frame_bgr, bytes) or not frame_bgr:
            raise ISRecognitionError("a non-empty exact BGR frame is required")
        pre = self._operator.capture_bgr(fresh=True)
        if pre is None or hashlib.sha256(pre).digest() != hashlib.sha256(frame_bgr).digest():
            raise StaleRecognitionError("supplied frame is not the fresh MaaCore frame")
        events = self._operator.run([("Custom", {"enable": True, "task_names": [self._overlay.host_task]})], timeout=30.0)
        post = self._operator.capture_bgr(fresh=True)
        if post is None or hashlib.sha256(pre).digest() != hashlib.sha256(post).digest():
            raise StaleRecognitionError("frame changed during MaaCore recognition")
        recognition_clips = tuple(
            c for c in clips
            if isinstance(c, Mapping) and isinstance(c.get("payload"), Mapping)
            and c["payload"].get("algorithm") in {"MatchTemplate", "OcrDetect"}
        )
        by_job = {_job_id(str(c["task_id"])): c for c in recognition_clips}
        findings: list[RecognizedClipV1] = []
        seen: set[str] = set()
        for event in events:
            message = self._event_value(event, "message")
            if message != MaaMessage.SubTaskStart and getattr(message, "name", None) != "SubTaskStart" and message != "SubTaskStart":
                continue
            details = self._event_value(event, "details")
            if not isinstance(details, Mapping):
                raise ISRecognitionError("malformed SubTaskStart evidence")
            job, result = _callback_job_and_result(
                details, set(by_job), self._overlay.host_task, self._overlay.sentinel_task
            )
            if job is None:  # Exact host/sentinel callback is not recognition evidence.
                continue
            if job in seen:
                raise ISRecognitionError("duplicate MaaCore recognition evidence")
            seen.add(job)
            rect, score, text = _validate_callback_result(result)
            clip = by_job[job]
            task_id, screen = clip.get("task_id"), clip.get("screen")
            if not isinstance(task_id, str) or not isinstance(screen, str):
                raise ISRecognitionError("malformed compiled clip")
            target_id = hashlib.sha256(
                (task_id + ":" + repr((rect.x, rect.y, rect.width, rect.height))).encode()
            ).hexdigest()[:32]
            # A private sentinel is converted to the sole reviewed binding below;
            # it is never part of the contestant-facing action surface.
            target = RecognitionTargetV1(target_id, None, "recognized", rect)  # type: ignore[arg-type]
            findings.append(RecognizedClipV1(task_id, hashlib.sha256(pre).hexdigest(), (target,), text))
        return findings


def _callback_job_and_result(
    details: Mapping[str, object], jobs: set[str], host_task: str, sentinel_task: str
) -> tuple[str | None, Mapping[str, object]]:
    """Accept one unambiguous generated job, or one exact host/sentinel event.

    A callback which names an ``Omni@ISR-`` task is never ambient noise: a
    typo/collision must close recognition rather than make a positive match vanish.
    """
    candidates: list[tuple[str, Mapping[str, object]]] = []
    names: list[str] = []

    def walk(value: object) -> None:
        if isinstance(value, Mapping):
            name = value.get("task") or value.get("task_name")
            if isinstance(name, str):
                names.append(name)
                if name in jobs:
                    result = value.get("result")
                    if not isinstance(result, Mapping):
                        raise ISRecognitionError("recognition callback has no result")
                    candidates.append((name, result))
                elif name.startswith("Omni@ISR-") and name not in {host_task, sentinel_task}:
                    raise ISRecognitionError("unknown generated recognition task callback")
            for child in value.values():
                walk(child)
        elif isinstance(value, list):
            for child in value:
                walk(child)

    walk(details)
    if not candidates:
        if any(name not in {host_task, sentinel_task} for name in names):
            raise ISRecognitionError("callback does not identify a generated recognition task")
        return None, {}
    if len(candidates) != 1:
        raise ISRecognitionError("ambiguous recognition callback evidence")
    return candidates[0]


def _validate_callback_result(result: Mapping[str, object]) -> tuple[PixelRectV1, float, tuple[str, ...]]:
    rect = result.get("rect")
    score = result.get("score")
    if not (isinstance(rect, list) and len(rect) == 4 and all(isinstance(n, int) and not isinstance(n, bool) for n in rect)):
        raise ISRecognitionError("callback rect must be canonical [x,y,width,height]")
    x, y, w, h = rect
    if x < 0 or y < 0 or w <= 0 or h <= 0 or x + w > 1280 or y + h > 720:
        raise ISRecognitionError("callback rect is outside the canonical frame")
    if not isinstance(score, (int, float)) or isinstance(score, bool) or not math.isfinite(score) or not 0 <= score <= 1:
        raise ISRecognitionError("callback score is invalid")
    raw_text = result.get("text", result.get("ocr_text", []))
    if isinstance(raw_text, str): texts = (raw_text,)
    elif isinstance(raw_text, list) and all(isinstance(v, str) for v in raw_text): texts = tuple(raw_text)
    else: raise ISRecognitionError("callback OCR text is malformed")
    return PixelRectV1(x, y, w, h), float(score), texts


class MAAISRecognizer:
    """Index a reviewed bundle and turn exact-frame results into IS observations."""
    def __init__(self, bundle: InteractionAssetBundleV1 | Mapping[str, object], engine: RecognitionEngine, *, internal_only_bypass: bool = False, ledger_sink: Callable[[Mapping[str, object]], object] | None = None, now: Callable[[], datetime] = lambda: datetime.now(UTC)) -> None:
        payload = _as_bundle(bundle)
        try: assert_maa_is_interaction_asset_bundle(payload)
        except MaaInteractionAssetError as exc: raise ISRecognitionError(str(exc)) from exc
        pending = payload["pending_reasons"]
        if not isinstance(pending, list): raise ISRecognitionError("invalid pending reasons")
        other = [r for r in pending if r != "maa_redistribution_review_pending"]
        if other: raise ISRecognitionError("bundle is not activatable")
        if "maa_redistribution_review_pending" in pending:
            if not internal_only_bypass or ledger_sink is None: raise ISRecognitionError("internal-only redistribution bypass and ledger sink are required")
            fact = {"schema": "omnicompany.arknights.maa-is-internal-bypass-ledger.v1", "bundle_sha256": InteractionAssetBundleV1(payload).content_sha256, "source_commit": payload["source"]["source_commit"], "scope": "internal_only", "deferred_review": "maa_redistribution_review_pending", "timestamp": now().astimezone(UTC).isoformat()}
            try: recorded = ledger_sink(fact)
            except Exception as exc: raise ISRecognitionError("internal bypass ledger append failed") from exc
            if recorded is not True: raise ISRecognitionError("internal bypass ledger append was not acknowledged")
        elif internal_only_bypass: raise ISRecognitionError("approved bundle must not request a redistribution bypass")
        clips, templates = payload["task_clips"], payload["templates"]
        if not isinstance(clips, list) or not isinstance(templates, list): raise ISRecognitionError("invalid compiled inventory")
        self.task_clips, self._payload, self._engine = tuple(clips), payload, engine
        self.clips_by_id = {str(c["task_id"]): c for c in clips if isinstance(c, Mapping)}
        self.template_hashes = {str(t["name"]): str(t["sha256"]) for t in templates if isinstance(t, Mapping)}
        self._bindings_by_task: dict[str, set[ISActionKind]] = {}
        for binding in payload["bindings"]:
            for task_id in binding["source_tasks"]: self._bindings_by_task.setdefault(str(task_id), set()).add(ISActionKind(str(binding["semantic_action"])))
        if len(self.clips_by_id) != len(clips) or len(self.template_hashes) != len(templates): raise ISRecognitionError("compiled inventory has duplicate or malformed ids")

    def observe(self, frame_bgr: bytes) -> ISObservationV1:
        digest = hashlib.sha256(frame_bgr).hexdigest()
        try: results = tuple(self._engine.recognize(frame_bgr, self.task_clips))
        except StaleRecognitionError: raise
        except Exception as exc: raise ISRecognitionError("recognition engine failed") from exc
        grouped: dict[ISScreenKind, list[RecognizedClipV1]] = {}
        for result in results:
            if not isinstance(result, RecognizedClipV1) or result.task_id not in self.clips_by_id or result.frame_sha256 != digest: raise ISRecognitionError("recognizer returned stale or unknown clip")
            try: screen = ISScreenKind(str(self.clips_by_id[result.task_id].get("screen")))
            except ValueError as exc: raise ISRecognitionError("compiled clip has invalid screen") from exc
            grouped.setdefault(screen, []).append(result)
        if len(grouped) != 1: raise ISRecognitionError("recognition produced no unique current visible screen")
        screen, matched = next(iter(grouped.items())); targets: list[VisibleTargetV1] = []; text: list[str] = []; seen: set[str] = set()
        for result in matched:
            text.extend(result.visible_text)
            actions = self._bindings_by_task.get(result.task_id, set())
            for target in result.targets:
                action = target.action
                if action is None:
                    if len(actions) != 1: raise ISRecognitionError("recognized clip has ambiguous reviewed actions")
                    action = next(iter(actions))
                if action not in actions or target.target_id in seen: raise ISRecognitionError("unbound or duplicate recognition target")
                seen.add(target.target_id); gesture = DirectGestureKind.SWIPE if target.end_rect else DirectGestureKind.TAP
                targets.append(VisibleTargetV1(target.target_id, action, target.label, target.rect, target.enabled, gesture, target.end_rect, target.duration_ms))
        return build_observation(screen=screen, frame_bytes=frame_bgr, visible_text=tuple(text), targets=targets)


def _safe_swipe_payload(payload: Mapping[str, object]) -> bool:
    start, end, params = payload.get("specificRect"), payload.get("rectMove"), payload.get("specialParams")
    return payload.get("action") == "Swipe" and all(isinstance(v, list) and len(v) == 4 and all(isinstance(n, int) and n >= 0 for n in v) for v in (start, end, params)) and start[2] > 0 and start[3] > 0 and end[2] > 0 and end[3] > 0 and params[0] > 0


class DirectScreenIO:
    def __init__(self, operator: MaaOperator, recognizer: MAAISRecognizer, swipe_invoker: SwipeTaskInvoker) -> None:
        self._operator, self._swipe_invoker, self._swipes = operator, swipe_invoker, {}
        for binding in recognizer._payload["bindings"]:
            for task_id in binding["source_tasks"]:
                clip = recognizer.clips_by_id[str(task_id)]; payload = clip["payload"]
                if isinstance(payload, Mapping) and _safe_swipe_payload(payload):
                    a, b, p = payload["specificRect"], payload["rectMove"], payload["specialParams"]
                    self._swipes[(a[0]+a[2]//2,a[1]+a[3]//2,b[0]+b[2]//2,b[1]+b[3]//2,p[0])] = (str(task_id), payload)
    def current_frame_sha256(self) -> str:
        frame = self._operator.capture_bgr(fresh=True)
        if not frame: raise ISRecognitionError("MAA did not provide a fresh BGR frame")
        return hashlib.sha256(frame).hexdigest()
    def capture_after_action_sha256(self) -> str: return self.current_frame_sha256()
    def tap(self, x: int, y: int) -> None:
        if not self._operator.tap(x, y): raise ISRecognitionError("MAA tap failed")
    def swipe(self, x: int, y: int, x2: int, y2: int, duration_ms: int) -> None:
        task = self._swipes.get((x,y,x2,y2,duration_ms))
        if task is None or not self._swipe_invoker(*task): raise ISRecognitionError("gesture is not a reviewed semantic Swipe task")


def maa_custom_swipe_invoker(operator: MaaOperator) -> SwipeTaskInvoker:
    def invoke(task_id: str, _payload: Mapping[str, object]) -> bool:
        return bool(operator.run([("Custom", {"enable": True, "task_names": [task_id]})], timeout=30.0))
    return invoke
