from __future__ import annotations

from copy import deepcopy
from typing import Any


def _profile(
    title: str,
    summary: str,
    player_goal: str,
    steps: tuple[str, ...],
    concepts: tuple[tuple[str, str], ...],
    rules: tuple[tuple[str, str], ...],
    connections: tuple[tuple[str, str], ...] = (),
) -> dict[str, Any]:
    return {
        "title": title,
        "summary": summary,
        "player_goal": player_goal,
        "steps": list(steps),
        "concepts": [
            {
                "id": f"concept-{index}",
                "name": name,
                "description": description,
            }
            for index, (name, description) in enumerate(concepts, start=1)
        ],
        "rules": [
            {"title": rule_title, "description": description}
            for rule_title, description in rules
        ],
        "connections": [
            {"play_slug": play_slug, "relationship": relationship}
            for play_slug, relationship in connections
        ],
    }


