_INTERNAL_MARKERS = (
    "agent",
    "ai 玩家",
    "evidencerun",
    "evidencestep",
    "partial",
    "candidate",
    "qualified",
    "0-token",
    "待证",
    "证据空位",
    "不宣称",
    "不作为",
    "未执行",
)


def _clean_fallback(value: Any) -> str:
    text = " ".join(str(value or "").split())
    if not text:
        return ""
    lowered = text.casefold()
    if any(marker in lowered for marker in _INTERNAL_MARKERS):
        return ""
    return text


def _fallback_profile(bundle: dict[str, Any]) -> dict[str, Any]:
    play = bundle.get("play") if isinstance(bundle.get("play"), dict) else {}
    scope = bundle.get("scope") if isinstance(bundle.get("scope"), dict) else {}
    design = (
        bundle.get("design_document")
        if isinstance(bundle.get("design_document"), dict)
        else {}
    )
    definition = (
        design.get("system_definition")
        if isinstance(design.get("system_definition"), dict)
        else {}
    )
    title = (
        _clean_fallback(definition.get("title"))
        or _clean_fallback(play.get("title"))
        or _clean_fallback(scope.get("subject"))
        or "游戏系统"
    )
    summary = (
        _clean_fallback(definition.get("definition"))
        or _clean_fallback(scope.get("coverage"))
        or f"介绍{title}的玩家目标、使用流程、关键概念和主要规则。"
    )
    tags = [str(tag) for tag in play.get("tags", []) if str(tag).strip()]
    concepts = [
        {
            "id": f"concept-{index}",
            "name": tag,
            "description": f"{title}中与“{tag}”相关的核心概念。",
        }
        for index, tag in enumerate(tags[:4], start=1)
    ]
    if not concepts:
        concepts = [
            {
                "id": "concept-1",
                "name": title,
                "description": f"本文介绍的核心游戏系统。",
            }
        ]
    return {
        "title": title,
        "summary": summary,
        "player_goal": f"理解{title}能解决什么问题，并完成一次完整的玩家流程。",
        "steps": [
            "进入系统并查看当前状态。",
            "选择目标和可用操作。",
            "完成操作并查看结果。",
            "根据结果继续推进或调整。",
        ],
        "concepts": concepts,
        "rules": [
            {
                "title": "先理解当前状态",
                "description": "页面状态、资源和目标共同决定当前可用操作。",
            },
            {
                "title": "结果推动下一步",
                "description": "完成操作后，玩家根据新的状态继续推进。",
            },
        ],
        "connections": [],
    }


def build_reader_projection(
    bundle: dict[str, Any],
    *,
    position: dict[str, Any] | None = None,
) -> dict[str, Any]:
    play = bundle.get("play") if isinstance(bundle.get("play"), dict) else {}
    slug = str(play.get("slug") or "")
    profile = deepcopy(READER_PLAY_PROFILES.get(slug) or _fallback_profile(bundle))
    profile["slug"] = slug
    resolved_position = deepcopy(position) if isinstance(position, dict) else {}
    profile["kind"] = str(
        resolved_position.get("label")
        or (
            "入门路线"
            if str(bundle.get("content_kind") or "") == "journey"
            else "待归类内容"
        )
    )
    profile["position"] = resolved_position

    for connection in profile["connections"]:
        related = READER_PLAY_PROFILES.get(str(connection.get("play_slug") or ""))
        connection["title"] = related["title"] if related else str(connection["play_slug"])

    return profile


def build_reader_game_projection(bundle: dict[str, Any]) -> dict[str, str]:
    game = bundle.get("game") if isinstance(bundle.get("game"), dict) else {}
    slug = str(game.get("slug") or game.get("id") or "")
    profile = READER_GAME_PROFILES.get(slug)
    if profile:
        return dict(profile)
    title = (
        _clean_fallback(game.get("localized_title"))
        or _clean_fallback(game.get("title"))
        or "游戏"
    )
    return {
        "title": title,
        "summary": f"查看《{title}》的系统、规则、界面和相关玩法。",
    }
